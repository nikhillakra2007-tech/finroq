/**
 * Universal Fallback & Automatic Translation Rule
 * Automatically resolves strings when switching languages even if a new key or fallback text is provided.
 */
export function applyAutomaticLanguageRule(lang: Language, key: string, fallback?: string): string | null {
  if (lang === 'en') return null;

  // 1. Direct key match in Universal UI translations
  const universalDict = UNIVERSAL_UI_TRANSLATIONS[lang];
  if (universalDict && universalDict[key]) {
    return universalDict[key];
  }

  // 2. Direct key match in Flagship translations
  const flagDict = FLAGSHIP_TRANSLATIONS[lang];
  if (flagDict && flagDict[key]) {
    return flagDict[key];
  }

  // 3. Fallback text lookup
  if (fallback) {
    const trimmedFallback = fallback.trim();

    // Check if universal English translations match the fallback
    const universalEn = UNIVERSAL_UI_TRANSLATIONS['en'];
    if (universalEn && universalDict) {
      for (const [k, v] of Object.entries(universalEn)) {
        if (v.toLowerCase() === trimmedFallback.toLowerCase() && universalDict[k]) {
          return universalDict[k];
        }
      }
    }

    // Check if flagship English translations match the fallback
    const enDict = FLAGSHIP_TRANSLATIONS['en'];
    if (enDict && flagDict) {
      for (const [k, v] of Object.entries(enDict)) {
        if (v.toLowerCase() === trimmedFallback.toLowerCase() && flagDict[k]) {
          return flagDict[k];
        }
      }
    }

    // Dynamic rule: "All X Features" / "All X Financial Engines"
    if (/All\s+\d+\s+(Features|Financial Engines)/i.test(fallback)) {
      return (flagDict && flagDict['common.all_features']) || (universalDict && universalDict['common.all_features']) || null;
    }
  }

  return null;
}

